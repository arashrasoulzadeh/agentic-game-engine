import 'dart:convert';

import 'package:engine_core/engine_core_ops.dart';

String _paramLine(Param p) {
  final bits = <String>[
    p.type.name,
    if (p.required) 'required',
    if (p.defaultValue != null) 'default `${jsonEncode(p.defaultValue)}`',
    if (p.min != null || p.max != null) '${p.min ?? '−∞'} to ${p.max ?? '∞'}',
    if (p.options.isNotEmpty)
      'one of ${p.options.map((o) => '`$o`').join(', ')}',
  ];
  final desc = p.description.isEmpty ? '' : ' ${p.description}';
  return '| `${p.name}` | ${bits.join('; ')} |${desc.replaceAll('\n', ' ').replaceAll('|', r'\|')} |';
}

String _cli(Operation op) {
  final group = op.cli.group ?? op.group;
  final verb = op.cli.verb ?? op.verb.replaceAll('_', '-');
  final positional = [
    for (final p in op.params)
      if (p.positional) '<${p.name}>',
  ];
  return 'game_agent $group $verb${positional.isEmpty ? '' : ' ${positional.join(' ')}'}';
}

/// The reference page for every operation, generated from the registry so it cannot drift from the code.
///
/// Flutter-dependent operations are listed separately because they exist only as CLI commands.
String renderOperationsReference(OperationRegistry registry) {
  final b = StringBuffer()
    ..writeln('# Operations')
    ..writeln()
    ..writeln(
      '<!-- Generated by `dart run tool/gen_api_docs.dart` in packages/engine_api. Do not edit. -->',
    )
    ..writeln()
    ..writeln(
      'Every operation is a CLI command, an MCP tool, a REST route and a JSON-RPC method. Reads change nothing; writes '
      'apply immediately and can be undone with `undo.undo`; destructive writes return a preview and a confirmation '
      'token first. Results are `{ok, data, warnings, diff?, undoId?, durationMs}` or `{ok:false, error:{code, message, hint?}}`.',
    )
    ..writeln();
  final groups = <String, List<Operation>>{};
  for (final op in registry.all) {
    (groups[op.group] ??= []).add(op);
  }
  for (final entry in groups.entries) {
    b
      ..writeln('## ${entry.key}')
      ..writeln();
    for (final op in entry.value) {
      b
        ..writeln('### `${op.name}`')
        ..writeln()
        ..writeln(op.summary)
        ..writeln();
      if (op.description.isNotEmpty)
        b
          ..writeln(op.description)
          ..writeln();
      b.writeln(
        '*${op.kind.name}*'
        '${op.scope == OperationScope.project ? ', needs an open project' : ''}'
        '${op.idempotent ? ', idempotent' : ''}'
        '${op.requiresFlutter ? ', **CLI only (needs the Flutter SDK)**' : ''}.',
      );
      b.writeln();
      final params = [...op.params, ...op.implicitParams];
      if (params.isNotEmpty) {
        b
          ..writeln('| Parameter | Type | Description |')
          ..writeln('|---|---|---|');
        for (final p in params) {
          b.writeln(_paramLine(p));
        }
        b.writeln();
      }
      if (op.errors.isNotEmpty) {
        b.writeln(
          'Errors: ${op.errors.keys.map((c) => '`${c.code}`').join(', ')}.',
        );
        b.writeln();
      }
      b
        ..writeln('```bash')
        ..writeln(_cli(op))
        ..writeln('```');
      if (!op.requiresFlutter) {
        b
          ..writeln()
          ..writeln(
            'REST: `POST /v1/${op.group}/${op.verb}` · MCP tool: `${op.name}` · JSON-RPC method: `${op.name}`',
          );
      }
      b.writeln();
    }
  }
  return b.toString();
}
