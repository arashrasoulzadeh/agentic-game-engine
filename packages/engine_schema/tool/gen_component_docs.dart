// Regenerates docs/reference/components.md from the component schemas.
//
//   dart run tool/gen_component_docs.dart > ../../docs/reference/components.md
//
// The schemas are the single source of truth for what each component's
// JSON looks like (see docs/adr/0001), so this page cannot drift from them.
import 'dart:io';

import 'package:engine_schema/engine_schema.dart';

const _groups = <(String, String, String)>[
  ('core_schemas.dart', 'engine_core', 'Genre-general data. Registered by `registerCoreComponents`.'),
  ('flutter_schemas.dart', 'engine_flutter', 'Rendering and input data. Registered by `registerFlutterComponents` (called for you by `GameRunner`).'),
  ('platformer_schemas.dart', 'engine_platformer', 'Platformer gameplay data. Registered by `registerPlatformerComponents`.'),
  ('idle_schemas.dart', 'engine_idle', 'Idle-game data. Registered by `registerIdleComponents`.'),
];

String _describe(FieldSchema f) {
  final bits = <String>[];
  if (f.required) bits.add('required');
  if (f.optional) bits.add('may be null');
  if (f.min != null || f.max != null) {
    bits.add('${f.min ?? '−∞'} to ${f.max ?? '∞'}');
  }
  if (f.options.isNotEmpty) bits.add('one of ${f.options.map((o) => '`$o`').join(', ')}');
  if (f.defaultValue != null) bits.add('default `${f.defaultValue}`');
  return bits.join('; ');
}

void main() {
  final out = StringBuffer()
    ..writeln('# Component reference')
    ..writeln()
    ..writeln('<!-- Generated by packages/engine_schema/tool/gen_component_docs.dart. Do not edit. -->')
    ..writeln()
    ..writeln('Every built-in component and the exact JSON shape it serializes to — what you see in '
        '`World.toJson()` and what `applyPatch` / `Level.loadInto` accept. '
        'This page is generated from `engine_schema`, the same schemas the studio and `game_agent lint` '
        'validate against, so it is always current.')
    ..writeln()
    ..writeln('**${allComponentSchemas.length} components** across ${_groups.length} packages. '
        'Jump to: ${_groups.map((g) => '[${g.$2}](#${g.$2.replaceAll('_', '_')})').join(' · ')}')
    ..writeln();

  final assigned = <String>{};
  for (final (file, pkg, blurb) in _groups) {
    final text = File('lib/src/$file').readAsStringSync();
    final names = RegExp(r"ComponentSchema\(\s*'([A-Za-z0-9]+)'")
        .allMatches(text)
        .map((m) => m.group(1)!)
        .toList();
    out
      ..writeln('## $pkg')
      ..writeln()
      ..writeln(blurb)
      ..writeln();
    for (final name in names) {
      final schema = allComponentSchemas[name];
      if (schema == null) continue;
      assigned.add(name);
      out.writeln('### `$name`');
      out.writeln();
      if (schema.fields.isEmpty) {
        out.writeln('A marker: present or absent, no fields.');
      } else {
        out
          ..writeln('| Field | Type | Notes |')
          ..writeln('|---|---|---|');
        for (final f in schema.fields) {
          out.writeln('| `${f.name}` | `${f.type.name}` | ${_describe(f)} |');
        }
      }
      out.writeln();
    }
  }
  stdout.write(out);
  final missing = allComponentSchemas.keys.where((k) => !assigned.contains(k));
  if (missing.isNotEmpty) {
    stderr.writeln('Not grouped (add a group in this tool): ${missing.join(', ')}');
    exitCode = 1;
  }
}
